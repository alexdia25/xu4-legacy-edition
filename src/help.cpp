/*
 * Tips for a new player, one topic to a chapter.  Like the guide, they
 * point the way without giving the answers away.
 */
static const char tipsText[] =
"FIRST STEPS\n"
"\n"
"  * Talk to everyone in the town you start near.  Ask about the words\n"
"    in their answers, and the Journal keeps what matters.\n"
"  * Lord British's castle stands beside the town of Britain.  Ask him\n"
"    for HELP when unsure what to do next: his advice changes as the\n"
"    quest goes on.\n"
"  * Buy food before anything else, then the best armour you can.\n"
"  * Save outdoors (Q, or Save Game in this menu) before a long trip.\n"
"\n"
"\n"
"TALKING\n"
"\n"
"  * NAME, JOB and HEALTH work with almost anyone.  A word in an answer\n"
"    is usually worth asking about too.\n"
"  * Ask JOIN of someone who might travel with you.  Some will only\n"
"    come once you are experienced and virtuous enough.\n"
"  * Answer questions as the Avatar would: honestly and humbly.  Proud\n"
"    or untrue answers cost virtue.\n"
"  * With the console menus, the action menu offers the words a person\n"
"    has spoken of, so nothing needs to be typed.\n"
"\n"
"\n"
"VIRTUE\n"
"\n"
"  * Giving to beggars, fighting evil creatures to the end and paying\n"
"    a blind shopkeeper fairly all count in your favour.\n"
"  * Stealing, attacking the peaceful, running from evil foes and\n"
"    boasting all count against you.\n"
"  * Hawkwind the seer, in Lord British's castle, tells how you stand in\n"
"    each virtue.  The Journal shows it as a word too.\n"
"\n"
"\n"
"SHRINES\n"
"\n"
"  * Each virtue has a shrine, out in the wilds.  Entering it needs the\n"
"    rune of that virtue.\n"
"  * Meditate there with the virtue's mantra, which people will teach\n"
"    you, for one to three cycles.  A vision may follow.\n"
"  * When the Journal says Ready for a virtue, meditating at its shrine\n"
"    elevates you in it.\n"
"\n"
"\n"
"FOOD AND GOLD\n"
"\n"
"  * Food runs down as you travel, faster with a bigger party.  Without\n"
"    it the party starves and loses hit points.\n"
"  * Grocers sell food; pubs and taverns sell it too, and tell tales.\n"
"  * Gold comes from the chests foes leave behind.  Get (G) a chest to\n"
"    open it, but beware of traps.  A chest in a town is not yours.\n"
"\n"
"\n"
"HEALING\n"
"\n"
"  * Healers in the towns cure poison, heal and even raise the dead,\n"
"    for gold.\n"
"  * Lord British heals the whole party, freely: ask him about HEAL.\n"
"  * Camping (H) outdoors or in a dungeon heals a little, and an inn\n"
"    more, if nothing finds you while you rest.\n"
"  * The Heal and Cure spells are cheap and worth keeping mixed.\n"
"\n"
"\n"
"MAGIC\n"
"\n"
"  * Reagents are sold in a few towns.  The Book of Mystic Wisdom tells\n"
"    which a spell needs; Mix (M) it before you cast (C).\n"
"  * Two reagents are never sold.  People know where they grow.\n"
"  * Magic points come back slowly as you travel and rest.  A mage has\n"
"    the most, a fighter or shepherd none.\n"
"  * With Spell Info In Lists, the party panel shows what a spell does,\n"
"    costs and needs while you choose.\n"
"\n"
"\n"
"LEVELS\n"
"\n"
"  * Experience comes from battle.  Levels 2 to 8 need 100, 200, 400,\n"
"    800, 1600, 3200 and 6400 points.\n"
"  * Only Lord British raises a level, when you visit him.  Each level\n"
"    gives 100 more hit points at most.\n"
"  * With Party Colours on, a name turns blue when a level is due.\n"
"\n"
"\n"
"TRAVEL\n"
"\n"
"  * Horses are sold in some towns and move the party faster.\n"
"  * Ships are taken from pirates: defeat a pirate ship's crew, then\n"
"    Board (B) it.  Fire (F) its cannons broadside.\n"
"  * Moongates open as the moons Trammel and Felucca turn.  The phases\n"
"    at the top of the screen tell where a gate will lead.\n"
"  * The World Map shows the places you have been near.\n"
"\n"
"\n"
"DUNGEONS\n"
"\n"
"  * Bring torches, or keep the Light spell mixed: dungeons are dark.\n"
"  * Klimb (K) a ladder up and Descend (D) one down.\n"
"  * A gem, Peered at (P), shows the level from above.  The Dungeon Map\n"
"    option keeps the rooms you have seen.\n"
"  * Fountains, altars and strange stones lie deep below.  Some are\n"
"    worth a search (S).\n"
"\n"
"\n"
"WHEN STUCK\n"
"\n"
"  * Open the Journal: each place shows how many of its clues you have\n"
"    heard, and with Journal Hints whom you have yet to ask.\n"
"  * Ask Lord British for HELP, and Hawkwind about your virtues.\n"
"  * The Hints book among the Books of Britannia answers the hard\n"
"    questions, if you would rather know.\n";

std::string legacyTipsText()
{
    return tipsText;
}

