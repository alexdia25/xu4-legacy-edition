#include <string>
#include "legacy.h"

static const char helpText[] =
"GETTING STARTED\n"
"\n"
"You begin in the lands of Britannia, often near your home town, with\n"
"a little food and gold.  There is no single path to follow: the game is\n"
"about becoming a person others look up to, and the way there is found\n"
"by talking to the people of Britannia.\n"
"\n"
"A good first hour:\n"
"\n"
"  * Walk into the nearest town and talk to everyone you meet.\n"
"  * Buy food at a grocer before it runs out, and better arms and\n"
"    armour when you can afford them.\n"
"  * Visit Lord British in his castle in Britain.  He will heal you\n"
"    and tell you of the quest.\n"
"  * Look for companions.  Some people will join you if you ask them\n"
"    to, once you are experienced enough.\n"
"\n"
"Save often with Q (or Save Game in the menu).  The game can be saved\n"
"outdoors and in dungeons, but not inside towns, castles or battles.\n"
"\n"
"\n"
"TALKING TO PEOPLE\n"
"\n"
"Talk (T) to someone next to you, then type a word to ask about.  Most\n"
"people answer NAME, JOB and HEALTH.  Their answers mention other words:\n"
"ask about those too, and write down anything that sounds important.\n"
"BYE ends the talk.\n"
"\n"
"Some people will ask you a question.  Answer honestly, as the Avatar\n"
"would.  Clues people give you about the quest are kept in the Journal.\n"
"\n"
"With the action menu (Tab, or the X button) the words a person\n"
"has talked about are offered as a list, so nothing needs to be typed.\n"
"\n"
"\n"
"THE CONTROLS\n"
"\n"
"Keyboard\n"
"\n"
"  Arrow keys        Walk, or turn and step in a dungeon\n"
"  A to Z            The commands of the Keyboard book\n"
"  Enter             The obvious action: board, klimb, descend...\n"
"  Tab               The action menu of everything you can do\n"
"  Space             Pass a turn\n"
"  Escape            This menu\n"
"  Alt-J             The Journal\n"
"  Alt-H             A summary of the keys\n"
"\n"
"Gamepad\n"
"\n"
"  Stick or D-pad    Walk\n"
"  A                 The obvious action, like Enter\n"
"  B                 Back out of a question or menu, or pass a turn\n"
"  X                 The action menu\n"
"  Y                 The world map\n"
"  L                 The world map\n"
"  Start             Pause\n"
"  Select            This menu\n"
"\n"
"Mouse and touch\n"
"\n"
"  Click or tap beside the party to walk that way, and on the party to\n"
"  open the action menu.  The icon at the top left opens this menu.\n"
"\n"
"\n"
"THE QUEST IN BRIEF\n"
"\n"
"The eight virtues are Honesty, Compassion, Valor, Justice, Sacrifice,\n"
"Honor, Spirituality and Humility.  Everything you do is weighed\n"
"against them: giving to beggars, fighting bravely and telling the truth\n"
"raise them; stealing, boasting and attacking the innocent lower them.\n"
"The Journal shows how far along the path of each virtue you are.\n"
"\n"
"Each virtue has a shrine.  To meditate there you need the rune of that\n"
"virtue and its mantra, both of which you must find.  When a virtue is\n"
"shown as Ready in the Journal, meditating at its shrine will elevate\n"
"you in it.\n"
"\n"
"Beyond the virtues lie the stones, the Bell, Book and Candle, and the\n"
"parts of a key, all of which are needed at the end of the quest.  The\n"
"people of Britannia know where to look.\n"
"\n"
"\n"
"STAYING ALIVE\n"
"\n"
"  * Food: the party eats as it travels.  Without food it starves and\n"
"    loses hit points.  Grocers sell food in most towns.\n"
"  * Healing: camp (H) to rest, stay at an inn, or visit a healer.\n"
"    Healers also cure poison and can raise the dead.\n"
"  * Poison: a poisoned member loses hit points every turn until cured\n"
"    with the Cure spell or by a healer.\n"
"  * Light: dungeons are dark.  Ignite a torch (I) or cast Light, and\n"
"    keep some torches in reserve.\n"
"  * Fleeing: a member leaves a battle by walking off its edge.  Running\n"
"    from a fight is not the way of Valor.\n"
"  * Experience: levels come from experience in battle.  Lord British\n"
"    raises the level of each member who has earned it when you visit\n"
"    him.\n"
"\n"
"\n"
"USING MAGIC\n"
"\n"
"A spell must be mixed before it can be cast.  Buy reagents at a\n"
"reagent shop, then Mix (M) the spell by choosing its reagents.  The\n"
"Book of Mystic Wisdom gives the reagents of every spell.  Two of the\n"
"eight reagents cannot be bought and must be found.\n"
"\n"
"Cast (C) a mixed spell by choosing who casts it and the spell.  Each\n"
"spell uses magic points, which return slowly as you travel.  Mages\n"
"have the most magic points, while fighters and shepherds have none.\n"
"\n"
"With Spell Info In Lists on, the spell lists show what each spell\n"
"does and what it costs, and ? (R on a gamepad, a right click, or\n"
"holding a finger on it) on a spell or reagent in a list opens its\n"
"page in the Book of Mystic Wisdom.\n"
"\n"
"\n"
"TRAVELLING BRITANNIA\n"
"\n"
"  * The two moons, Trammel and Felucca, open moongates at night.  The\n"
"    phases shown at the top of the screen tell where a gate leads.\n"
"  * Horses can be bought, and ships are taken from the pirates who\n"
"    sail them.  Board (B) to use them and X to get off.\n"
"  * Fire (F) a ship's cannons broadside, to its left or right.\n"
"  * A sextant lets you Locate (L) your position on the map.\n"
"  * The world map (in this menu, or the L button) shows Britannia,\n"
"    with the runes of the map translated as you go.\n"
"\n"
"\n"
"LEGACY EDITION OPTIONS\n"
"\n"
"Settings, then Legacy Edition Options, holds the conveniences of this\n"
"edition.  Most start on; Walk Into To Act starts on when a gamepad\n"
"is used, and Auto Combat and Pause When Unfocused start off:\n"
"\n"
"  Walk Into To Act       Walking into someone talks, into a foe\n"
"                         attacks, into a locked door opens it.\n"
"  Fold Repeated Moves    \"North (x5)\" instead of five lines.\n"
"  Cancel Spends No Turn  Backing out of a command costs nothing.\n"
"  Shops Compare Arms     Shops show how gear compares with what each\n"
"                         member has, and offer to equip it.\n"
"  Spell Info In Lists    Spell lists say what each spell does, and\n"
"                         ? opens the spell in the Book of Wisdom.\n"
"  Heal In Action Menu    A Heal shortcut when someone is hurt.\n"
"  Auto Combat            The party fights on its own.\n"
"  Dungeon Map            A mini map or a top-down view of dungeons.\n"
"  Pause When Unfocused   The game waits while you are away.\n"
"\n"
"Rules, Saving & Cheats sets the difficulty (Classic is the game as it\n"
"was, Modern and Story are gentler), autosave with a history of saves,\n"
"several characters with their own saves, and what happens when the\n"
"party falls.  Scanlines and Battery Saver are in the Graphics options.\n";

std::string legacyHelpText()
{
    return helpText;
}
